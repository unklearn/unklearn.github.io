export type Item = 'apple' | 'carrot';
export type Place = 'noticeboard' | 'pantry' | 'picnic_basket';
export type Point = [number, number, number];
export type Inventory = Record<Item, number>;
export type Mode = 'mock' | 'live' | 'replay';
export interface Snapshot {
  notice: string;
  position: Point;
  place: Place | null;
  pantry: Inventory;
  carried: Item | null;
  basket: Inventory;
}
export interface ToolCall { function: { name: string; arguments: Record<string, unknown> } }
export interface Message {
  role: 'system' | 'user' | 'assistant' | 'tool';
  content: string;
  tool_calls?: ToolCall[];
  tool_name?: string;
  thinking?: string;
}
export interface ToolDefinition {
  type: 'function';
  function: { name: string; description: string; parameters: Record<string, unknown> };
}
export type Provider = (messages: readonly Message[], tools: readonly ToolDefinition[], signal: AbortSignal) => Promise<Message>;
export interface Clock { now(): number; sleep(ms: number, signal: AbortSignal): Promise<void> }
export interface Movement { path: Point[]; duration: number }
export interface WorldEvent { kind: string; text: string; state: Snapshot; movement?: Movement }
export interface TraceEvent extends WorldEvent {
  seq: number;
  at: number;
  turn?: number;
  tool?: ToolCall['function'];
  result?: Record<string, unknown>;
}
export interface Trace {
  version: 1;
  id: string;
  mode: 'mock' | 'live';
  provider: string;
  startedAt: string;
  order: string;
  initial: Snapshot;
  events: TraceEvent[];
  final?: Snapshot;
  status: string;
}

